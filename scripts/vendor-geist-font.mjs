import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const sourcePath = join(
  process.cwd(),
  "node_modules",
  "next",
  "dist",
  "compiled",
  "@vercel",
  "og",
  "Geist-Regular.ttf",
);
const outputPath = join(
  process.cwd(),
  "convex",
  "assets",
  "geistRegularBase64.ts",
);
const bytes = await readFile(sourcePath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const chunks = bytes
  .toString("base64")
  .match(/.{1,120}/gu)
  ?.map((chunk) => `  "${chunk}",`)
  .join("\n");

if (!chunks) {
  throw new Error("Geist font could not be encoded.");
}

const source = `/**
 * Generated by scripts/vendor-geist-font.mjs.
 * Source: https://github.com/vercel/geist-font
 * Local source: Next.js compiled @vercel/og Geist-Regular.ttf
 * SHA-256: ${sha256}
 * License: SIL Open Font License 1.1, see convex/assets/GEIST-OFL.txt.
 */
export const geistRegularBase64 = [
${chunks}
].join("");
`;

await writeFile(outputPath, source, "utf8");
